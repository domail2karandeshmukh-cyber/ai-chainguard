"""Write report/sections/90_references.tex: the references of the final report in order of first citation.

    python report/tools/order_refs.py

Reads the \\input order of final_report.tex, collects the \\cite keys of each section in order of first
appearance and takes the matching \\bibitem entries from references_src.tex. Stops on a key that is cited
but not defined, and on an entry that is defined but never cited.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPORT = Path(__file__).resolve().parents[1]
OUT = REPORT / "sections" / "90_references.tex"


def main() -> int:
    main_tex = (REPORT / "final_report.tex").read_text()
    order: list[str] = []
    for name in re.findall(r"\\input\{(sections/[^}]+)\}", main_tex):
        if name.endswith("90_references"):
            continue
        text = (REPORT / f"{name}.tex").read_text()
        text = re.sub(r"(?m)(?<!\\)%.*$", "", text)
        for group in re.findall(r"\\cite\{([^}]+)\}", text):
            for key in (k.strip() for k in group.split(",")):
                if key not in order:
                    order.append(key)
    src = (REPORT / "references_src.tex").read_text()
    entries = {m.group(1): m.group(0).strip() for m in re.finditer(r"(?m)^\\bibitem\{([^}]+)\}.*$", src)}
    missing = [k for k in order if k not in entries]
    unused = [k for k in entries if k not in order]
    if missing or unused:
        print("cited but not defined:", missing, "| defined but never cited:", unused, file=sys.stderr)
        return 1
    lines = [
        "% Generated by report/tools/order_refs.py from references_src.tex. Do not edit by hand.",
        "\\FloatBarrier\\needspace{12\\baselineskip}",
        "\\addsec{References}\\label{sec:refs}\\vspace{-0.45\\baselineskip}%",
        "{\\color{cgrule}\\rule{\\textwidth}{0.6pt}}\\par\\vspace{0.15\\baselineskip}",
        "{\\sffamily\\fontsize{8.5}{11.3}\\selectfont\\setlength{\\itemsep}{2.2pt}\\raggedright",
        "\\makeatletter\\renewcommand*{\\bib@heading}{}\\makeatother",
        "\\begin{thebibliography}{99}",
        "\\setlength{\\itemsep}{2.2pt}\\setlength{\\parskip}{0pt}",
        *[entries[k] for k in order],
        "\\end{thebibliography}}",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"{OUT.relative_to(REPORT)}: {len(order)} references in order of first citation")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
