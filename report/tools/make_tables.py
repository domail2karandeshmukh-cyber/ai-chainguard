"""Write the generated tables of the final report from results/.

    python report/tools/make_tables.py

Output: report/sections/gen_variants.tex, the list of the 48 variants (Appendix B), from results/attacks/summary.csv.
"""

from __future__ import annotations

import csv
from pathlib import Path

REPORT = Path(__file__).resolve().parents[1]
ROOT = REPORT.parent
CHIP = {"VERIFIED": "\\cVER", "FAILED": "\\cFAIL", "WARNING": "\\cWARN", "REFUSED": "\\cREF"}
EXPERIMENT = {"A": "Experiment 1: dataset tampering (scenario A)", "B": "Experiment 2: model substitution (scenario B)",
              "D": "Experiment 3: invalid signature and key misuse (scenario D)",
              "C": "Experiment 4: broken provenance (scenario C)",
              "F": "Experiment 5: revocation and its bypasses (scenario F)",
              "E": "Experiment 6: poison before signing (scenario E)",
              "G": "Experiment 7: untrusted external source (scenario G)"}


def tex(s: str) -> str:
    s = s.replace(" -> ", ": ").replace("LIMITATION: ", "Limit: ").replace("BLOCKED", "blocked")
    s = s.replace("1e-6", "$10^{-6}$").replace("(v0.3 limitation)", "(the limitation of version 0.3)")
    for a, b in (("&", "\\&"), ("%", "\\%"), ("_", "\\_"), ("#", "\\#")):
        s = s.replace(a, b)
    return s


def main() -> None:
    with (ROOT / "results" / "attacks" / "summary.csv").open(newline="") as fh:
        rows = list(csv.DictReader(fh))
    out = ["% Generated by report/tools/make_tables.py from results/attacks/summary.csv. Do not edit by hand."]
    for sc in "ABDCFEG":
        out.append(f"\\midrule\\multicolumn{{5}}{{l}}{{\\textbf{{\\color{{cgnavy}}{EXPERIMENT[sc]}}}}} \\\\*")
        group = [x for x in rows if x["scenario"] == sc]
        for n, r in enumerate(group):
            checks = ", ".join((r["failed_checks"] + " " + r["warned_checks"]).split()) or "none"
            assert r["expected"] == r["observed"], r
            keep = "" if n == len(group) - 1 else "*"  # a page break only between two experiments
            out.append(f"{r['variant']} & {tex(r['title'])} & {CHIP[r['observed']]} & {checks} & "
                       f"{float(r['detection_ms']):.1f} \\\\{keep}")
    (REPORT / "sections" / "gen_variants.tex").write_text("\n".join(out) + "\n")
    print(f"sections/gen_variants.tex: {len(rows)} variants")


if __name__ == "__main__":
    main()
